const CACHE = {};
function glyph(ch) {
  if (!(ch in CACHE)) CACHE[ch] = G[ch] ? G[ch].split(',') : null;
  return CACHE[ch];
}

export const CHAR_W = 4;      // 3px glyph + 1px gap
export const CHAR_H = 6;      // 5px glyph + 1px gap

export function textWidth(str, scale = 1) { return str.length * CHAR_W * scale; }

export function drawText(ctx, str, x, y, colour = '#fff', scale = 1, shadow = null) {
  str = String(str).toUpperCase();
  if (shadow) drawText(ctx, str, x, y + scale, shadow, scale, null);
  ctx.fillStyle = colour;
  let cx = x;
  for (const ch of str) {
    const rows = glyph(ch);
    if (rows) {
      for (let ry = 0; ry < 5; ry++) {
        const row = rows[ry];
        for (let rx = 0; rx < 3; rx++) {
          if (row[rx] === '#') ctx.fillRect(cx + rx * scale, y + ry * scale, scale, scale);
        }
      }
    }
    cx += CHAR_W * scale;
  }
  return cx;
}
